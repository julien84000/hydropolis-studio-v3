const canonical=s=>String(s||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
function resolve(family,category){
 const key=canonical(family);
 if(!key||!['showers','baths','basins'].includes(category))return null;
 const list=RECORDS.filter(r=>r.category===category);
 // The strongest match is the specific named manufacturer product on the same category.
 const exact=list.find(r=>canonical(r.name)===key);
 if(exact)return {...exact,scope:'model-only'};
 // Manufacturer may call the priced family « BetteFloor Side avec système ... »
 // while its published product is called « BetteFloor Side ».
 const prefixes=list.filter(r=>key.startsWith(canonical(r.name)+' ')).sort((a,b)=>canonical(b.name).length-canonical(a.name).length);
 if(prefixes.length)return {...prefixes[0],scope:'family'};
 // Generic model for an unqualified tariff family, only if the model root matches.
 // Avoid picking a bath illustration for a shower or confusing Floor vs Floor Side.
 const sub=list.filter(r=>canonical(r.name).startsWith(key+' '));
 const distinct=new Set(sub.map(r=>canonical(r.name).split(' ').slice(0,2).join(' ')));
 if(sub.length&&distinct.size===1)return {...sub[0],scope:'family'};
 return null;
}
return {records:RECORDS,resolve,canonical};
